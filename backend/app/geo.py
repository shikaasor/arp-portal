"""States, LGAs and wards, and the matching rules used to scope reviewers.

`geo.json` holds every LGA and ward in the states the programme covers, taken from GRID3 NGA
Operational Wards v4.0 (CC BY-SA 4.0; credited on the site). It is generated by
scripts/build_geo.py, and the frontend ships an identical copy (frontend/src/lib/geo.json) that a
test keeps in step.

Applicants pick their LGA and ward from those lists, so new applications store one canonical
spelling. Older rows and reviewer assignments were typed, so every comparison still goes through
`geo_key`, which ignores case, spaces and punctuation; the database computes the same key in the
generated columns `lga_key` and `ward_key`. LGAs also accept the other spellings listed in
`lga_aliases` (GRID3's alternative names and the portal's earlier spellings), so an application or
assignment saved under an older LGA name still matches.
"""

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

_NON_ALNUM = re.compile(r"[^a-z0-9]+")


def geo_key(value: str | None) -> str:
    """Matching key: lowercase letters and digits only. Mirrors the SQL in the migrations."""
    return _NON_ALNUM.sub("", (value or "").lower())


def tidy(value: str) -> str:
    """Collapse runs of whitespace, as typed values are stored."""
    return " ".join(value.split())


@lru_cache
def geo_data() -> dict[str, Any]:
    return json.loads((Path(__file__).parent / "geo.json").read_text(encoding="utf-8"))


@lru_cache
def lgas_by_state() -> dict[str, tuple[str, ...]]:
    return {state: tuple(info["lgas"]) for state, info in geo_data()["states"].items()}


@lru_cache
def wards_by_lga(state: str, lga: str) -> tuple[str, ...]:
    """The wards of an LGA, given its official spelling."""
    return tuple(geo_data()["states"].get(state, {}).get("lgas", {}).get(lga, ()))


@lru_cache
def _lga_lookup(state: str) -> dict[str, str]:
    """Every accepted key for an LGA in `state` -> its official spelling."""
    aliases = geo_data()["lga_aliases"].get(state, {})
    lookup = {geo_key(alias): lga for alias, lga in aliases.items()}
    lookup.update({geo_key(lga): lga for lga in lgas_by_state().get(state, ())})
    return lookup


def canonical_lga(state: str | None, lga: str | None) -> str | None:
    """The official spelling of `lga` in `state`, or None if it is not one of that state's LGAs."""
    key = geo_key(lga)
    return _lga_lookup(state or "").get(key) if key else None


def lga_match_keys(state: str | None, lga: str | None) -> tuple[str, ...]:
    """Keys under which applications for this LGA may be stored: the official name and every
    accepted other spelling. An LGA not on the list falls back to its own key."""
    official = canonical_lga(state, lga)
    if official is None:
        return (geo_key(lga),) if geo_key(lga) else ()
    return tuple(sorted(k for k, name in _lga_lookup(state or "").items() if name == official))


def canonical_ward(state: str | None, lga: str | None, ward: str | None) -> str | None:
    """The official spelling of `ward` in that LGA, or None if it is not one of its wards."""
    key = geo_key(ward)
    official_lga = canonical_lga(state, lga)
    if not key or official_lga is None:
        return None
    return next(
        (name for name in wards_by_lga(state or "", official_lga) if geo_key(name) == key), None
    )
