#!/usr/bin/env python3
"""Build responsive, optimised WebP images + a typed manifest from scripts/images.json.

Run once when images change (outputs are committed):
    python3 scripts/build-images.py

Each entry in images.json:
  key, file (source under scripts/image-src/, or a repo-relative "assets/..." path), alt, widths,
  crop ("x,y,w,h" fractions, optional), gallery (optional group name, e.g. "senate")
  and credit fields: title, creator, creator_url, license, license_url, source_url.
If a source file is missing (originals are not committed), the existing outputs in public/img are
reused so the manifest can still be regenerated.
We self-host the files (no hotlinking) and serve them unoptimised by Next.js, because the
/_next/image optimiser is not available under Vercel Services routing.
"""

import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
SRC = ROOT / "scripts" / "image-src"
OUT = ROOT / "public" / "img"
MANIFEST = ROOT / "src" / "lib" / "images.generated.ts"


def render(e: dict, src: Path) -> list[tuple[int, int, str]]:
    im = ImageOps.exif_transpose(Image.open(src))
    im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
    if e.get("crop"):
        x, y, w, h = (float(v) for v in e["crop"].split(","))
        W, H = im.size
        im = im.crop((int(x * W), int(y * H), int((x + w) * W), int((y + h) * H)))
    variants = []
    for width in e["widths"]:
        width = min(width, im.width)
        h = round(im.height * width / im.width)
        name = f"{e['key']}-{width}.webp"
        im.resize((width, h), Image.LANCZOS).save(OUT / name, "WEBP", quality=e.get("quality", 74), method=6)
        variants.append((width, h, name))
    return variants


def existing(key: str) -> list[tuple[int, int, str]]:
    variants = []
    for f in OUT.glob(f"{key}-*.webp"):
        suffix = f.stem[len(key) + 1:]
        if suffix.isdigit():
            with Image.open(f) as im:
                variants.append((im.width, im.height, f.name))
    if not variants:
        raise SystemExit(f"{key}: no source file and no existing outputs in {OUT}")
    return variants


def main() -> None:
    entries = json.loads((ROOT / "scripts" / "images.json").read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by scripts/build-images.py — do not edit by hand.",
        "export type SiteImage = {",
        "  src: string; srcSet: string; width: number; height: number; alt: string; gallery?: string;",
        "  credit?: { title: string; creator: string; creatorUrl?: string; license: string;",
        "    licenseUrl: string; sourceUrl: string };",
        "};",
        "",
        "export const images = {",
    ]
    for e in entries:
        src = REPO / e["file"] if e["file"].startswith("assets/") else SRC / e["file"]
        if src.exists():
            variants = render(e, src)
        else:
            variants = existing(e["key"])
            print(f"{e['key']:<18} source missing, reusing existing outputs")
        variants = sorted(set(variants))
        w, h, largest = variants[-1]
        mid = next((v for v in variants if v[0] >= 1200), variants[-1])
        src_set = ", ".join(f"/img/{n} {vw}w" for vw, _, n in variants)
        credit = ""
        if e.get("creator"):
            c = {
                "title": e["title"], "creator": e["creator"], "license": e["license"],
                "licenseUrl": e["license_url"], "sourceUrl": e["source_url"],
            }
            if e.get("creator_url"):
                c["creatorUrl"] = e["creator_url"]
            credit = f", credit: {json.dumps(c, ensure_ascii=False)}"
        gallery = f", gallery: {json.dumps(e['gallery'])}" if e.get("gallery") else ""
        lines.append(
            f"  {e['key']!s}: {{ src: \"/img/{mid[2]}\", srcSet: \"{src_set}\", width: {w}, "
            f"height: {h}, alt: {json.dumps(e['alt'], ensure_ascii=False)}{gallery}{credit} }},"
        )
        total = sum((OUT / n).stat().st_size for _, _, n in variants) // 1024
        print(f"{e['key']:<18} {len(variants)} sizes, {total} KB total")
    lines += ["} satisfies Record<string, SiteImage>;", "", "export type ImageKey = keyof typeof images;", ""]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
